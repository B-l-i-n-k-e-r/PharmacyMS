// 1. Financial Summary
try {
    $revQuery = $con->query("SELECT SUM(amount) as total_rev, COUNT(*) as total_sales FROM receipts");
    $finance = $revQuery->fetch(PDO::FETCH_ASSOC);
    $total_revenue = $finance['total_rev'] ?: 0;
    $total_sales = $finance['total_sales'] ?: 0;
    $avg_order = $total_sales > 0 ? ($total_revenue / $total_sales) : 0;
} catch (PDOException $e) { 
    $total_revenue = 0; $total_sales = 0; $avg_order = 0; 
}

// 2. Stock Valuation & Count
try {
    $stockQuery = $con->query("SELECT SUM(quantity) as total_items, SUM(quantity * cost) as total_value FROM stock");
    $stockData = $stockQuery->fetch(PDO::FETCH_ASSOC);
    $total_items = $stockData['total_items'] ?: 0;
    $total_value = $stockData['total_value'] ?: 0;
} catch (PDOException $e) { 
    $total_items = 0; $total_value = 0; 
}

// 3. Top 5 Premium Products
try {
    $topQuery = $con->query("SELECT drug_name, quantity, cost FROM stock ORDER BY cost DESC LIMIT 5");
